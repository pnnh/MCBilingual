#!/usr/bin/env python3
"""Build rich entries.tsv from ECDICT CSV by contemporary frequency rank (frq).

Keeps lemmas with 1 <= frq <= LIMIT (default 60000), non-empty Chinese translation.
Does not randomly sample — lower frq = more common.

Usage:
  python tools/dictionary/build_ecdict_tsv.py --csv path/to/ecdict.csv
  python tools/dictionary/build_ecdict_tsv.py --download
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
import urllib.request
from pathlib import Path

# Raise field size for long ECDICT rows
csv.field_size_limit(min(sys.maxsize, 2**31 - 1))

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "src/main/resources/data/mcbilingual/dictionary/entries.tsv"
DEFAULT_LIMIT = 60_000
ECDICT_CSV_URL = (
    "https://raw.githubusercontent.com/skywind3000/ECDICT/master/ecdict.csv"
)

HEADER = (
    "# ECDICT-derived learner lexicon (MIT).\n"
    "# Top {limit} single-token lemmas by frq (fallback bnc), ascending rank.\n"
    "# Format: word<TAB>phonetic<TAB>pos<TAB>exchange<TAB>translation\n"
    "# Generated by tools/dictionary/build_ecdict_tsv.py — do not hand-edit at scale.\n"
)


def download_csv(dest: Path) -> Path:
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"Downloading {ECDICT_CSV_URL} -> {dest} ...", flush=True)
    urllib.request.urlretrieve(ECDICT_CSV_URL, dest)
    print(f"Downloaded {dest.stat().st_size} bytes", flush=True)
    return dest


def parse_rank(raw: str) -> int | None:
    if raw is None:
        return None
    s = str(raw).strip()
    if not s or s == "0":
        return None
    try:
        value = int(s)
    except ValueError:
        return None
    return value if value > 0 else None


def row_rank(row: dict[str, str]) -> int | None:
    """Prefer contemporary frq; fall back to BNC rank when frq missing."""
    frq = parse_rank(row.get("frq", ""))
    if frq is not None:
        return frq
    return parse_rank(row.get("bnc", ""))


def sanitize_field(value: str) -> str:
    if not value:
        return ""
    # Keep single-line TSV cells; senses stay as \n escapes for WordCardFormatter
    return (
        value.replace("\r\n", "\n")
        .replace("\r", "\n")
        .replace("\t", " ")
        .replace("\n", "\\n")
        .strip()
    )


def build(csv_path: Path, out_path: Path, limit: int) -> int:
    # headword_lower -> (rank, word, phonetic, pos, exchange, translation)
    best: dict[str, tuple[int, str, str, str, str, str]] = {}

    with csv_path.open("r", encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        required = {"word", "translation", "frq"}
        if not required.issubset(set(reader.fieldnames or [])):
            raise SystemExit(f"CSV missing columns {required}: {reader.fieldnames}")

        for row in reader:
            rank = row_rank(row)
            if rank is None:
                continue
            word = (row.get("word") or "").strip()
            translation = (row.get("translation") or "").strip()
            if not word or not translation:
                continue
            # Skip multi-word phrases — freeze word mode tokens are single spans
            if " " in word or "\t" in word:
                continue
            key = word.lower()
            phonetic = sanitize_field(row.get("phonetic") or "")
            pos = sanitize_field(row.get("pos") or "")
            exchange = sanitize_field(row.get("exchange") or "")
            translation = sanitize_field(translation)
            prev = best.get(key)
            if prev is None or rank < prev[0]:
                best[key] = (rank, word, phonetic, pos, exchange, translation)

    ranked = sorted(best.values(), key=lambda item: (item[0], item[1].lower()))
    if len(ranked) > limit:
        ranked = ranked[:limit]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="\n") as out:
        out.write(HEADER.format(limit=limit))
        for rank, word, phonetic, pos, exchange, translation in ranked:
            out.write(f"{word}\t{phonetic}\t{pos}\t{exchange}\t{translation}\n")

    print(f"Wrote {len(ranked)} entries to {out_path}", flush=True)
    if ranked:
        print(f"rank range: {ranked[0][0]} .. {ranked[-1][0]}", flush=True)
    return len(ranked)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, help="Path to ecdict.csv")
    parser.add_argument(
        "--download",
        action="store_true",
        help=f"Download ECDICT CSV to tools/dictionary/.cache/ecdict.csv",
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--limit", type=int, default=DEFAULT_LIMIT)
    args = parser.parse_args(argv)

    csv_path = args.csv
    if args.download or csv_path is None:
        cache = REPO_ROOT / "tools/dictionary/.cache/ecdict.csv"
        if args.download or not cache.is_file():
            download_csv(cache)
        csv_path = cache
    if not csv_path.is_file():
        raise SystemExit(f"CSV not found: {csv_path}")

    count = build(csv_path, args.out, args.limit)
    if count < 50_000:
        print(f"WARNING: only {count} entries (expected near {args.limit})", flush=True)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
